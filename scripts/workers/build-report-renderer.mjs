/** Reviewed portable bundle: exact Dashboard pure projection, never DOM/3D. */
import { createRequire } from 'node:module';
import { readFile,writeFile,mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const require=createRequire(import.meta.url), viteRequire=createRequire(require.resolve('vite/package.json'));
const esbuild=viteRequire('esbuild');
const result=await esbuild.build({entryPoints:['src/lib/workers/report-pdf.ts'],bundle:true,write:false,format:'esm',platform:'neutral',target:'es2022',external:['jspdf','jspdf-autotable'],metafile:true});
const inputs=await Promise.all(Object.keys(result.metafile.inputs).sort().map(async p=>[p,createHash('sha256').update(await readFile(p)).digest('hex')]));
const body='// AUTO-GENERATED by scripts/workers/build-report-renderer.mjs. Do not edit.\n// Inputs SHA256 '+createHash('sha256').update(JSON.stringify(inputs)).digest('hex')+'\n'+result.outputFiles[0].text;
const dest='supabase/functions/_shared/workers/generated/report-pdf.js';
if(process.argv.includes('--check')) {if(await readFile(dest,'utf8')!==body)throw Error('Report renderer bundle stale');}
else {await mkdir('supabase/functions/_shared/workers/generated',{recursive:true});await writeFile(dest,body);}

const logo='export const reportLogoDataUrl = '+JSON.stringify('data:image/png;base64,'+(await readFile('public/alvorada/fenasoja-symbol-official.png')).toString('base64'))+';\n';
const logoPath='supabase/functions/_shared/workers/generated/report-logo.ts';
if(process.argv.includes('--check')){if(await readFile(logoPath,'utf8')!==logo)throw Error('Report brand stale');}else await writeFile(logoPath,logo);
