const roundCoordinate = (value: number) => Number(value.toFixed(6));

export function electricalPlanPointToWorldXZ([pdfX, pdfY]: Coordinate): Coordinate {
  const matrix = ELECTRICAL_INFRASTRUCTURE_REFERENCE.calibration.pdfPagePointToWorldXZMatrix;
  return [
    roundCoordinate(matrix[0][0] * pdfX + matrix[0][1] * pdfY + matrix[0][2]),
    roundCoordinate(matrix[1][0] * pdfX + matrix[1][1] * pdfY + matrix[1][2]),
  ];
}

export function electricalPlanPointToOfficialPdf([pdfX, pdfY]: Coordinate): Coordinate {
  const matrix = ELECTRICAL_INFRASTRUCTURE_REFERENCE.calibration.a3PagePointToOfficialPdfPointMatrix;
  return [
    roundCoordinate(matrix[0][0] * pdfX + matrix[0][1] * pdfY + matrix[0][2]),
    roundCoordinate(matrix[1][0] * pdfX + matrix[1][1] * pdfY + matrix[1][2]),
  ];
}

function rotationAt(sourceIndex: number, source: readonly ElectricalSourceTuple[]) {
  const current = source[sourceIndex];
  let nearest: ElectricalSourceTuple | null = null;
  let nearestSquaredDistance = Number.POSITIVE_INFINITY;
  source.forEach((candidate, candidateIndex) => {
    if (candidateIndex === sourceIndex) return;
    const deltaX = candidate[1] - current[1];
    const deltaY = candidate[2] - current[2];
    const squaredDistance = deltaX * deltaX + deltaY * deltaY;
    if (squaredDistance < nearestSquaredDistance) {
      nearest = candidate;
      nearestSquaredDistance = squaredDistance;
    }
  });
  if (!nearest) return 0;
  const spanAngle = Math.atan2(nearest[2] - current[2], nearest[1] - current[1]);
  return roundCoordinate(Math.PI / 2 - spanAngle);
}

