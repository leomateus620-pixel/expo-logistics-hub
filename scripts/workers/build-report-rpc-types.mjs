/** Narrow, additive RPC typing from the reviewed report migration catalog. */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const sources = [
 'supabase/migrations/20261023140000_workers_commercial_report_query.sql',
 'supabase/migrations/20261023150000_workers_commercial_report_artifacts.sql',
 'supabase/migrations/20261023170000_workers_commercial_report_projection_parity.sql',
 'supabase/migrations/20261023190000_workers_commercial_report_selectors.sql',
 'supabase/migrations/20261023200000_workers_commercial_report_current_inventory.sql',
];
const authenticated = [
 'workers_commercial_report_authorize', 'workers_map_commercial_report',
 'workers_commercial_report_snapshot', 'workers_commercial_report_prepare',
 'workers_commercial_report_status', 'workers_commercial_report_download',
];
const service = [
 'workers_commercial_report_store', 'workers_commercial_report_claim',
 'workers_commercial_report_finish', 'workers_commercial_report_expired_files', 'workers_commercial_report_purge',
];
const types = { uuid:'string', text:'string', jsonb:'Json', boolean:'boolean', integer:'number' };
const definitions = new Map(), hashes = [];
for (const source of sources) {
 const text = await readFile(source,'utf8');hashes.push([source,createHash('sha256').update(text).digest('hex')]);
 for (const name of [...authenticated,...service]) {
  const match = text.match(new RegExp(`CREATE OR REPLACE FUNCTION public\\.${name}\\(([^)]*)\\)\\s*RETURNS\\s+(TABLE\\([^)]*\\)|jsonb|uuid|void)\\s+LANGUAGE`,'i'));
  if (!match)continue;
  const args = match[1].trim()?match[1].split(',').map(arg=>{
   const field=arg.trim().match(/^(\w+)\s+(uuid|text|jsonb|boolean|integer)(\s+DEFAULT\s+NULL)?$/i);
   if(!field)throw Error(`Unsupported argument contract in ${name}: ${arg}`);
   return `${field[1]}${field[3]?'?':''}: ${types[field[2].toLowerCase()]}${field[3]?' | null':''}`;
  }):[];
  let returns=match[2].toLowerCase()==='void'?'undefined':types[match[2].toLowerCase()];
  if(/^table\(/i.test(match[2]))returns='{ '+match[2].slice(6,-1).split(',').map(arg=>{
   const [key,type]=arg.trim().split(/\s+/);if(!types[type.toLowerCase()])throw Error(`Unsupported return type in ${name}`);
   return `${key}: ${types[type.toLowerCase()]}`;
  }).join('; ')+' }[]';
  if(!returns)throw Error(`Unsupported return contract in ${name}`);
  definitions.set(name,`  ${name}: { Args: ${args.length?'{ '+args.join('; ')+' }':'Record<string, never>'}; Returns: ${returns} };`);
 }
}
for(const name of [...authenticated,...service])if(!definitions.has(name))throw Error(`RPC missing from reviewed catalog: ${name}`);
const body=`// AUTO-GENERATED by scripts/workers/build-report-rpc-types.mjs. Do not edit.\n// Reviewed migration catalog SHA256 ${createHash('sha256').update(JSON.stringify(hashes)).digest('hex')}\nimport type { Json } from '@/integrations/supabase/types';\n\n/** Types do not grant access; every invocation still uses the caller's JWT and server authorization. */\nexport type CommercialReportRpcFunctions = {\n${authenticated.map(name=>definitions.get(name)).join('\n')}\n};\n\n/** Internal service functions are deliberately excluded from the browser client database type. */\nexport type CommercialReportServiceRpcFunctions = {\n${service.map(name=>definitions.get(name)).join('\n')}\n};\n`;
const target='src/features/workers/generated/commercialReportRpcTypes.ts';
if(process.argv.includes('--check')){if(await readFile(target,'utf8')!==body)throw Error('Commercial report RPC types are stale. Run scripts/workers/build-report-rpc-types.mjs.');}
else {await mkdir('src/features/workers/generated',{recursive:true});await writeFile(target,body);}
console.log(`Commercial report RPC types ${process.argv.includes('--check')?'verified':'generated'} (${authenticated.length} authenticated, ${service.length} service-only).`);
