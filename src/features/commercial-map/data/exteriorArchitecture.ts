export function exteriorIdHash(id: string): number {
  let hash = 2166136261;
  for (const ch of id) hash = Math.imul(hash ^ ch.charCodeAt(0), 16777619);
  return hash >>> 0;
}

/** Eligibility precedes hashing: no new occupation or residential -> industrial conversion. */
export function architectureForBuilding(
  building: TerritoryBuilding,
): ArchitectureModel {
  const family =
    building.kind === "shed"
      ? "shed"
      : building.id.startsWith("roadside-house-")
        ? "rural"
        : "house";
  const eligible = EXTERIOR_ARCHITECTURE_CATALOG.filter(
    (model) =>
      model.category === family &&
      (family !== "rural" || Number(model.id.slice(1)) <= 6) &&
      (model.floors === 1 || building.height >= 0.86) &&
      (building.size[0] / building.size[1] >= 0.58 ||
        !["U", "T"].includes(model.plan)),
  );
  return eligible[exteriorIdHash(building.id) % eligible.length];
}
