/* Browser-only synthetic identities and contracts. No remote backend writes. */
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs/promises');
const assert = require('node:assert/strict');
const path = require('node:path');
const output = path.resolve('docs/validation/pavilion-occupancy');
const base = process.env.OCCUPANCY_QA_URL || 'http://127.0.0.1:8080/scripts/dashboard/occupancy-qa.html';
(async () => {
  await fs.mkdir(output, { recursive: true });
  const browser = await chromium.launch({ headless: true, channel: 'chrome' });
  const page = await browser.newPage({ viewport: { width: 1600, height: 1080 }, deviceScaleFactor: 1 });
  const errors = [], checks = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.route('**/rest/v1/**', route => route.abort());
  await page.goto(base); await page.locator('[data-module-number]').first().waitFor();
  assert.equal(await page.locator('[data-module-number]').count(), 257);
  const geometry = await page.locator('path[data-entity-id]').evaluateAll(els => els.map(e => [e.dataset.entityId, e.getAttribute('d')]));
  const connections = await page.locator('[data-group-connection]').count();
  checks.push({ name: '257 cadastral lots and commercial SVG leaders', lots: geometry.length, connections });
  assert(connections > 0);
  await page.screenshot({ path: path.join(output, 'pavilion-12-default.png'), fullPage: true });
  await page.getByRole('button', { name: 'Tela cheia', exact: true }).click();
  const modal = page.getByRole('dialog'); await modal.waitFor();
  assert.equal(await modal.locator('[data-module-number]').count(), 257);
  await modal.locator('.pavilion-company-list button').filter({ hasText: 'ALFA MÁQUINAS' }).click();
  assert.match(await modal.locator('.pavilion-company-detail').innerText(), /Assinatura parcial/);
  assert.equal(await modal.locator('.pavilion-order').count(), 2);
  await modal.getByRole('button', { name: /Ampliar planta/ }).click();
  assert.equal(await modal.locator('.commercial-dashboard-map-surface').evaluate(e => e.style.width), '150%');
  await page.screenshot({ path: path.join(output, 'pavilion-12-fullscreen-selected.png') });
  await modal.getByRole('button', { name: 'Fechar tela cheia' }).click();
  await page.getByRole('button', { name: 'Tela cheia', exact: true }).waitFor();
  assert.equal(await page.locator('.commercial-dashboard-map-surface').evaluate(e => e.style.width), '150%');
  assert.equal(await page.evaluate(() => document.activeElement?.textContent), 'Tela cheia');
  checks.push({ name: 'fullscreen selection, mixed contracts, zoom persistence and focus restoration', passed: true });
  await page.getByRole('button', { name: /Limpar seleção da empresa/ }).click();
  await page.getByText('Visualização', { exact: true }).click();
  await page.getByLabel('Mostrar conexões').uncheck();
  assert.equal(await page.locator('[data-group-connection]').count(), 0);
  await page.getByLabel('Mostrar empresas').uncheck();
  assert.equal(await page.locator('[data-exhibitor-group]').count(), 0);
  assert.deepEqual(await page.locator('path[data-entity-id]').evaluateAll(els => els.map(e => [e.dataset.entityId, e.getAttribute('d')])), geometry);
  await page.getByRole('button', { name: 'Restaurar visualização padrão' }).click();
  await page.getByText('Visualização', { exact: true }).click();
  checks.push({ name: 'filters and hide/show preserve exact polygon paths', passed: true });
  const download12 = page.waitForEvent('download'); await page.getByRole('button', { name: 'Baixar planta em PDF' }).click();
  await (await download12).saveAs(path.join(output, 'pavilion-12-commercial.pdf'));
  await page.getByRole('checkbox', { name: 'Alta densidade' }).check();
  await page.locator('[data-module-number]').first().waitFor();
  const labelCount = await page.locator('.pavilion-annotation-label').count();
  assert.equal(labelCount, 8);
  await page.getByRole('button', { name: /^Expositores/ }).click();
  const totalGroups = await page.locator('.pavilion-company-list > button').count();
  assert(totalGroups > 40);
  await page.locator('.pavilion-company-list > button').last().click();
  await page.getByRole('button', { name: 'Tela cheia', exact: true }).click();
  await page.screenshot({ path: path.join(output, 'pavilion-12-dense.png') });
  await page.keyboard.press('Escape'); await page.getByRole('dialog').waitFor({ state: 'hidden' });
  checks.push({ name: 'high density uses 8 labels and retains all groups', totalGroups, labelCount });
  await page.getByRole('checkbox', { name: 'Alta densidade' }).uncheck();
  await page.getByRole('combobox', { name: 'Pavilhão de teste' }).selectOption('13');
  await page.waitForFunction(() => document.querySelectorAll('[data-module-number]').length === 104);
  const download13 = page.waitForEvent('download'); await page.getByRole('button', { name: 'Baixar planta em PDF' }).click();
  await (await download13).saveAs(path.join(output, 'pavilion-13-commercial.pdf'));
  await page.getByRole('button', { name: 'Tela cheia', exact: true }).click();
  await page.screenshot({ path: path.join(output, 'pavilion-13-fullscreen.png') });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(output, 'pavilion-13-mobile.png'), fullPage: true });
  const mobile = await page.locator('.pavilion-fullscreen').evaluate(e => ({ width: e.clientWidth, scrollWidth: e.scrollWidth, height: e.clientHeight }));
  assert(mobile.scrollWidth <= mobile.width + 1);
  await page.getByRole('dialog').getByRole('button', { name: /^Expositores/ }).click();
  await page.keyboard.press('Escape'); await page.getByRole('dialog').waitFor({ state: 'hidden' });
  checks.push({ name: 'Pavilion 13 has 104 original spaces, mobile fits viewport and Escape closes', mobile });
  assert.deepEqual(errors, []);
  await fs.writeFile(path.join(output, 'browser-report.json'), JSON.stringify({ boundary: 'Local browser, synthetic commercial records on official geometry; no production access.', checks, errors }, null, 2));
  console.log(JSON.stringify({ passed: true, checks, errors }, null, 2));
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
