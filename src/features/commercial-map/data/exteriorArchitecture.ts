import type { TerritoryBuilding } from "./territorialEnvironment";

export type ArchitectureCategory =
  | "house"
  | "rural"
  | "shed"
  | "building"
  | "support";
export type RoofForm = "gable" | "hip" | "mono" | "flat" | "saw" | "barrel";
export type PlanForm = "rectangle" | "L" | "T" | "U" | "stepped" | "twin";
export interface ArchitectureModel {
  id: string;
  name: string;
  category: ArchitectureCategory;
  plan: PlanForm;
  roof: RoofForm;
  floors: number;
  /** Width of the principal volume, depth, ridge rise, front bay count. */
  proportions: readonly [number, number, number, number];
  porch: "none" | "front" | "side" | "wrap";
  garage: boolean;
  balcony: boolean;
  finish: "ceramic" | "metal" | "cement" | "timber" | "brick";
}
type Recipe = readonly [
  string,
  PlanForm,
  RoofForm,
  number,
  number,
  number,
  number,
  number,
  ArchitectureModel["porch"],
  boolean?,
  boolean?,
  ArchitectureModel["finish"]?,
];
function category(
  category: ArchitectureCategory,
  prefix: string,
  recipes: readonly Recipe[],
): ArchitectureModel[] {
  return recipes.map(
    (
      [
        name,
        plan,
        roof,
        floors,
        width,
        depth,
        rise,
        bays,
        porch,
        garage = false,
        balcony = false,
        finish = "ceramic",
      ],
      i,
    ) => ({
      id: `${prefix}${String(i + 1).padStart(2, "0")}`,
      name,
      category,
      plan,
      roof,
      floors,
      proportions: [width, depth, rise, bays],
      porch,
      garage,
      balcony,
      finish,
    }),
  );
}

