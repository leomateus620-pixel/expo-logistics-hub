import { createRequire } from 'node:module';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const base = process.argv[2] || 'http://127.0.0.1:4181';
const output = process.argv[3] || 'artifacts/alvorada/handoff';
await fs.mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext({ viewport: { width: 1280, height: 720 }, recordVideo: { dir: output, size: { width: 1280, height: 720 } }, reducedMotion: 'reduce' });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.goto(`${base}/scripts/alvorada-qa.html`);
await page.waitForSelector('[data-renderer-state="webgl"]');
await page.waitForSelector('[data-stage="santa-rosa"]');
await page.waitForTimeout(900);
await page.screenshot({ path: `${output}/atmospheric-handoff.png` });
await page.waitForSelector('[data-stage="brand-hold"]');
assert.equal(await page.locator('canvas').count(), 0, 'hidden WebGL released at decoded harvest hold');
assert.equal(await page.locator('.alvorada-brand-hero').getByText('2028', { exact: true }).count(), 1);
await page.waitForSelector('.org-ecosystem[data-active="true"]');
const phaseAtInput = await page.getByTestId('alvorada-experience').getAttribute('data-stage');
assert.equal(phaseAtInput, 'org-transition');
await page.getByRole('combobox').fill('Felipe Bortoli');
await page.getByRole('option').first().click();
assert.equal(await page.locator('.org-detail').count(), 1);
assert.equal(await page.locator('[data-edge-id]').count(), 1);
await page.waitForSelector('[data-stage="org-ready"]');
await page.waitForTimeout(350);
await page.screenshot({ path: `${output}/selection-during-handoff.png` });
await page.getByRole('button', { name: 'Fechar detalhes', exact: true }).click();
await page.getByRole('button', { name: 'Fechar O Nascer da Alvorada', exact: true }).click();
await page.getByRole('button', { name: 'Reabrir avaliação' }).waitFor();
await page.getByRole('button', { name: 'Reabrir avaliação' }).click();
await page.waitForSelector('[data-renderer-state="webgl"]');
await page.getByRole('button', { name: 'Fechar O Nascer da Alvorada', exact: true }).click();
await page.getByRole('button', { name: 'Reabrir avaliação' }).waitFor();
assert.equal(await page.locator('canvas').count(), 0);
assert.deepEqual(errors, []);
await fs.writeFile(`${output}/checks.json`, JSON.stringify({ phaseAtInput, reducedMotion: true, checks: ['same complete journey with reduced-motion preference', 'atmospheric approach and harvest decoded', 'WebGL released while harvest holds', 'one 2028', 'search responds during graph reveal', 'only selected direct edge during reveal', 'close panel', 'close/reopen/close intro without stale resources'], errors }, null, 2));
await context.close();
const video = await page.video().path();
await fs.rename(video, `${output}/complete-journey.webm`);
await browser.close();
console.log('Complete handoff and close/reopen checks passed');
