function sourceDistance(left: CommercialElectricalNode, right: CommercialElectricalNode) {
  return Math.hypot(
    right.sourcePagePosition[0] - left.sourcePagePosition[0],
    right.sourcePagePosition[1] - left.sourcePagePosition[1],
  );
}

function addCanonicalEdge(
  edges: Map<string, ElectricalConnectionCandidate>,
  left: CommercialElectricalNode,
  right: CommercialElectricalNode,
  kind: CommercialElectricalConnectionKind,
  sourceAlignmentChainId: string | null = null,
) {
  if (left.id === right.id) return;
  const [fromNodeId, toNodeId] = left.id.localeCompare(right.id) <= 0
    ? [left.id, right.id]
    : [right.id, left.id];
  const key = `${fromNodeId}::${toNodeId}`;
  const existing = edges.get(key);
  if (!existing || kind === 'TRANSFORMER_SERVICE_DROP') {
    edges.set(key, {
      fromNodeId,
      toNodeId,
      kind,
      sourceAlignmentChainId,
      topologyEvidence: kind === 'PRIMARY_ALIGNMENT'
        ? 'RECIPROCAL_NEAREST_COLLINEAR_ALIGNMENT'
        : 'TRANSFORMER_PROXIMITY',
    });
  }
}

function properSourceSegmentIntersection(
  left: { fromNodeId: string; toNodeId: string },
  right: { fromNodeId: string; toNodeId: string },
) {
  if (
    left.fromNodeId === right.fromNodeId
    || left.fromNodeId === right.toNodeId
    || left.toNodeId === right.fromNodeId
    || left.toNodeId === right.toNodeId
  ) return false;
  const a = NODE_BY_ID.get(left.fromNodeId)?.sourcePagePosition;
  const b = NODE_BY_ID.get(left.toNodeId)?.sourcePagePosition;
  const c = NODE_BY_ID.get(right.fromNodeId)?.sourcePagePosition;
  const d = NODE_BY_ID.get(right.toNodeId)?.sourcePagePosition;
  if (!a || !b || !c || !d) return false;
  const orientation = (
    start: readonly [number, number],
    end: readonly [number, number],
    point: readonly [number, number],
  ) => (end[0] - start[0]) * (point[1] - start[1])
    - (end[1] - start[1]) * (point[0] - start[0]);
  const epsilon = 1e-7;
  const firstSide = orientation(a, b, c) * orientation(a, b, d);
  const secondSide = orientation(c, d, a) * orientation(c, d, b);
  return firstSide < -epsilon && secondSide < -epsilon;
}

function pruneIncoherentEdges(
  candidates: readonly ElectricalConnectionCandidate[],
) {
  const blockedPairs = new Set(
    ELECTRICAL_INFRASTRUCTURE_REFERENCE.topology.excludedObstructedPairs.map(({ sourceMarkerIds }) => (
      [...sourceMarkerIds].sort().join('::')
    )),
  );
  const isBlocked = (candidate: ElectricalConnectionCandidate) => {
    const sourcePair = [candidate.fromNodeId, candidate.toNodeId]
      .map((nodeId) => nodeId.replace(/^electrical-/, ''))
      .sort()
      .join('::');
    return blockedPairs.has(sourcePair);
  };
  // Establish the non-crossing topology against the complete candidate graph
  // first. Structural exclusions are then subtractive only: they can never
  // backfill a previously rejected crossing with an unsafe alternate span.
  const primaryByShortestSpan = candidates
    .filter((candidate) => candidate.kind === 'PRIMARY_ALIGNMENT')
    .sort((left, right) => {
      const leftFrom = NODE_BY_ID.get(left.fromNodeId)!;
      const leftTo = NODE_BY_ID.get(left.toNodeId)!;
      const rightFrom = NODE_BY_ID.get(right.fromNodeId)!;
      const rightTo = NODE_BY_ID.get(right.toNodeId)!;
      return sourceDistance(leftFrom, leftTo) - sourceDistance(rightFrom, rightTo)
        || left.fromNodeId.localeCompare(right.fromNodeId)
        || left.toNodeId.localeCompare(right.toNodeId);
    });
  const acceptedPrimary: typeof primaryByShortestSpan = [];
  primaryByShortestSpan.forEach((candidate) => {
    if (acceptedPrimary.some((accepted) => properSourceSegmentIntersection(candidate, accepted))) return;
    acceptedPrimary.push(candidate);
  });
  return [
    ...acceptedPrimary.filter((candidate) => !isBlocked(candidate)),
    ...candidates.filter((candidate) => (
      candidate.kind === 'TRANSFORMER_SERVICE_DROP' && !isBlocked(candidate)
    )),
  ];
}

function buildConnectionCandidates() {
  const edges = new Map<string, ElectricalConnectionCandidate>();
  const { maximumTransformerServiceSpanPdfPoints } = ELECTRICAL_INFRASTRUCTURE_REFERENCE.topology;

  COMMERCIAL_ELECTRICAL_ALIGNMENT_CHAINS.forEach(([chainId, , sourceMarkerIds]) => {
    sourceMarkerIds.slice(0, -1).forEach((sourceMarkerId, index) => {
      const nextSourceMarkerId = sourceMarkerIds[index + 1];
      const left = NODE_BY_SOURCE_MARKER_ID.get(sourceMarkerId);
      const right = NODE_BY_SOURCE_MARKER_ID.get(nextSourceMarkerId);
      if (!left || !right) {
        throw new Error(`Electrical alignment ${chainId} references an unknown marker: ${sourceMarkerId} -> ${nextSourceMarkerId}`);
      }
      addCanonicalEdge(edges, left, right, 'PRIMARY_ALIGNMENT', chainId);
    });
  });

  COMMERCIAL_ELECTRICAL_TRANSFORMERS.forEach((transformer) => {
    const nearest = COMMERCIAL_ELECTRICAL_POLES
      .map((pole) => ({ pole, distance: sourceDistance(transformer, pole) }))
      .filter((candidate) => candidate.distance <= maximumTransformerServiceSpanPdfPoints)
      .sort((left, right) => left.distance - right.distance || left.pole.id.localeCompare(right.pole.id))[0];
    if (nearest) addCanonicalEdge(edges, transformer, nearest.pole, 'TRANSFORMER_SERVICE_DROP');
  });
  return pruneIncoherentEdges([...edges.values()]).sort((left, right) => (
    left.fromNodeId.localeCompare(right.fromNodeId) || left.toNodeId.localeCompare(right.toNodeId)
  ));
}

function connectedCircuitByNode(
  candidates: readonly { fromNodeId: string; toNodeId: string }[],
) {
  const adjacency = new Map<string, Set<string>>();
  candidates.forEach((connection) => {
    if (!adjacency.has(connection.fromNodeId)) adjacency.set(connection.fromNodeId, new Set());
    if (!adjacency.has(connection.toNodeId)) adjacency.set(connection.toNodeId, new Set());
    adjacency.get(connection.fromNodeId)?.add(connection.toNodeId);
    adjacency.get(connection.toNodeId)?.add(connection.fromNodeId);
  });
  const circuitByNode = new Map<string, string>();
  let circuitIndex = 0;
  [...adjacency.keys()].sort().forEach((startNodeId) => {
    if (circuitByNode.has(startNodeId)) return;
    circuitIndex += 1;
    const circuitId = `electrical-circuit-${String(circuitIndex).padStart(3, '0')}`;
    const pending = [startNodeId];
    while (pending.length > 0) {
      const nodeId = pending.pop();
      if (!nodeId || circuitByNode.has(nodeId)) continue;
      circuitByNode.set(nodeId, circuitId);
      adjacency.get(nodeId)?.forEach((neighborId) => pending.push(neighborId));
    }
  });
  return circuitByNode;
}

